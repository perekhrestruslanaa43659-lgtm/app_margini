export function formatQuoteDate(d: string | null, lang: QuoteLang): string {
  if (!d) return ''
  return new Date(d).toLocaleDateString(lang === 'en' ? 'en-GB' : 'it-IT', { day: '2-digit', month: 'long', year: 'numeric' })
}

